    private static void register(Category category, String[] words) {
        CATEGORIES.put(category.key(), category);
        WORDS.put(category.key(), words);
    }

    private final Random random = new Random();

    public Iterable<Category> categories() {
        return CATEGORIES.values();
    }

    public Category category(String key) {
        return CATEGORIES.get(key);
    }

    public String randomWord(String key) {
        String[] words = WORDS.get(key);
        if (words == null) {
            return null;
        }
        return words[random.nextInt(words.length)];
    }

    /** Приводим слово к единому виду: верхний регистр, Ё -> Е. */
    public static String normalize(String s) {
        if (s == null) {
            return "";
        }
        return s.trim().toUpperCase().replace('Ё', 'Е');
    }
